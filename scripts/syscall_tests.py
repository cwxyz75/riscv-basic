#!/usr/bin/env python3
"""Every syscall error names a test (KT4). The errors of each call are the status names in its section of docs/reference/SYSCALLS.md;
`docs/reference/syscall-tests.tsv` has one row per (call, status): the call, the status, and a test of `init/src/bin/suite.rs` (or
`init/src/net_tests.rs`) whose body calls `sys::<call>(` and mentions the status (`S::BadHandle`, `Status::BadHandle`), or the word
UNTESTED. The check fails when an error in the reference has no row, a row names a test that does not exist or does not mention both,
or a row says UNTESTED for a pair a test now covers (so the table only gets better).

  syscall_tests.py            check (also run by `make docs-check`)
  syscall_tests.py --write    regenerate the table (keeps nothing by hand: the evidence is the source)
"""
import os, re, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DOC = os.path.join(ROOT, "docs/reference/SYSCALLS.md")
TSV = os.path.join(ROOT, "docs/reference/syscall-tests.tsv")
SUITES = ["init/src/bin/suite.rs", "init/src/net_tests.rs"]


def camel(name):
    return "".join(w.capitalize() for w in name.split("_"))


def statuses_of_doc(text):
    m = re.search(r"### Status codes\n(.*?)\n###", text, re.S)
    return [r.split("|")[1].strip() for r in m.group(1).splitlines() if re.match(r"\| [A-Z_]+ \|", r) and "| OK |" not in r]


def doc_pairs():
    text = open(DOC).read()
    names = statuses_of_doc(text)
    pairs = []
    for sec in re.split(r"\n### ", text)[1:]:
        head, _, body = sec.partition("\n")
        calls = re.findall(r"\b([a-z][a-z0-9_]*)\(", head.split("->")[0]) or []
        # "process_suspend(process) / process_resume(process)" and lists like "thread_yield(), clock_get(), ..."
        calls = [c for c in calls if c not in ("a", "n")]
        if not calls or "Errors" not in body and "errors" not in body:
            continue
        # the error sentences: from "Errors" to the end of the paragraph
        for para in re.split(r"\n\n", body):
            for m in re.finditer(r"[Ee]rrors?[^\n]*(?:\n(?!\n)[^\n]*)*", para):
                for st in re.findall(r"\b([A-Z][A-Z_]+[A-Z])\b", m.group(0)):
                    if st in names:
                        for c in calls:
                            pairs.append((c, st))
    return sorted(set(pairs))


def test_bodies():
    """name -> body, for every `fn` of the suite files (a test is a function; the registered ones are the tests)."""
    bodies = {}
    for f in SUITES:
        src = open(os.path.join(ROOT, f)).read()
        starts = [(m.group(1), m.start()) for m in re.finditer(r"\n(?:pub )?fn ([a-z0-9_]+)\(", src)]
        for i, (n, p) in enumerate(starts):
            e = starts[i + 1][1] if i + 1 < len(starts) else len(src)
            bodies[n] = src[p:e]
    return bodies


def covers(body, call, status):
    c = camel(status)
    return f"sys::{call}(" in body and re.search(rf"\b(?:S|Status)::{c}\b", body) is not None


def best_test(bodies, registered, call, status):
    cands = sorted(n for n, b in bodies.items() if n in registered and covers(b, call, status))
    return cands[0] if cands else None


def registered_tests():
    reg = set()
    for f in SUITES:
        src = open(os.path.join(ROOT, f)).read()
        reg |= set(re.findall(r'\(\s*"([a-z0-9_]+)",\s*[a-z0-9_:]+\s*,?\s*\)', src))
    return reg


def main():
    bodies, reg, pairs = test_bodies(), registered_tests(), doc_pairs()
    if "--write" in sys.argv:
        rows = [(c, s, best_test(bodies, reg, c, s) or "UNTESTED") for c, s in pairs]
        with open(TSV, "w") as f:
            f.write("# call\\tstatus\\ttest  (generated by scripts/syscall_tests.py --write; the check is scripts/syscall_tests.py)\n".replace("\\t", "\t"))
            for r in rows:
                f.write("\t".join(r) + "\n")
        print(f"{len(rows)} rows, {sum(1 for r in rows if r[2] == 'UNTESTED')} untested")
        return 0
    rows = {}
    for line in open(TSV):
        if line.startswith("#") or not line.strip():
            continue
        c, s, t = line.rstrip("\n").split("\t")
        rows[(c, s)] = t
    problems = []
    for c, s in pairs:
        if (c, s) not in rows:
            problems.append(f"syscall-tests.tsv: {c} {s} (an error SYSCALLS.md lists) has no row; run scripts/syscall_tests.py --write and look at the diff")
    for (c, s), t in rows.items():
        if (c, s) not in pairs:
            problems.append(f"syscall-tests.tsv: row {c} {s} is no longer an error SYSCALLS.md lists")
        elif t == "UNTESTED":
            if best_test(bodies, reg, c, s):
                problems.append(f"syscall-tests.tsv: {c} {s} is marked UNTESTED but {best_test(bodies, reg, c, s)} covers it: regenerate")
        elif t not in reg:
            problems.append(f"syscall-tests.tsv: {c} {s} names {t}, which is not a registered test of the suite")
        elif not covers(bodies.get(t, ""), c, s):
            problems.append(f"syscall-tests.tsv: {t} does not call sys::{c} and mention {s}")
    untested = sum(1 for t in rows.values() if t == "UNTESTED")
    if "--quiet" not in sys.argv:
        print(f"syscall errors: {len(pairs)} pairs, {len(pairs) - untested} with a test, {untested} untested (T-item: see work/)")
    for p in problems:
        print(p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
